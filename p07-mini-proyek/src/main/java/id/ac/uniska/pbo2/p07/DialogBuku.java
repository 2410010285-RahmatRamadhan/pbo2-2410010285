    private void tahunFieldKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_tahunFieldKeyTyped
        // Pencegahan kesalahan: tahun hanya menerima angka dan paling banyak 4 digit
        boolean penuh = tahunField.getText().length() >= 4
                && tahunField.getSelectedText() == null;
        if (!Character.isDigit(evt.getKeyChar()) || penuh) {
            evt.consume(); // karakter tidak dimasukkan ke isian
        }
    }//GEN-LAST:event_tahunFieldKeyTyped

